public class DemoCharArr 
{
    public static void main(String[] args) 
    {
        // Prints contents on char array
        char[] temp = {'A', 'B','C', 'D'};
        System.out.println(temp);

        // Prints text for string
        String name = "Java";
        System.out.println(name);

        // Prints address for int array
        int[] nums = {5, 4, 6};
        System.out.println(nums);

        String emoji = "😊";
        System.out.println(emoji.length());
    }
}
