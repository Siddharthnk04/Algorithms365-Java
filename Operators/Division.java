class Division 
{
    public static void main(String[] args) 
    {
        //Integer Division
        System.out.println(10/2);
        System.out.println(15/4);
        int a = 15;
        int b = 3;
        System.out.println(a/b);


        //Float Division

        System.out.println(15/4.0);

        float x = 12.0f;
        float y = 5.0f;
        System.out.println(x/y);
        System.out.println(a/x);
        


    }
}
