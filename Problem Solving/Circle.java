public class Circle 
{
    public static void main(String[] args) 
    {
        float radius = 4.525f;

        double circumference = 2*3.14*radius;
        double area = 3.14+radius+radius;

        System.err.println("Circumference of Circle : " + circumference);
        System.err.println();
        System.err.println("Area of Circle : " + area);
    }
}
